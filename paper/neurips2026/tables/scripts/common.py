"""Shared helpers for the table generators.

Every generator reads saved experiment outputs from an inputs directory (default: ../inputs) and
writes LaTeX tables into --out. No generator runs an estimator; each one only formats saved numbers.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

INPUTS = Path(__file__).resolve().parents[1] / "inputs"


def parse(description: str) -> argparse.Namespace:
    ap = argparse.ArgumentParser(description=description)
    ap.add_argument("--inputs", type=Path, default=INPUTS, help="directory with the saved outputs")
    ap.add_argument("--out", type=Path, required=True, help="directory for the generated .tex files")
    return ap.parse_args()


def load(inputs: Path, rel: str):
    return json.loads((inputs / rel).read_text())


def write(out: Path, name: str, body: str, script: str) -> None:
    """Write one table; the first line names its generator (a LaTeX comment)."""
    out.mkdir(parents=True, exist_ok=True)
    (out / name).write_text(f"% Generated by paper/neurips2026/tables/scripts/{script}\n" + body)
    print(f"wrote {out / name}")
